_WORD = re.compile(r"[а-яёa-z0-9]+(?:-[а-яёa-z0-9]+)?")


def _words(text: str) -> list[str]:
    return _WORD.findall((text or "").lower().replace("ё", "е"))


def _name_roots(name: str) -> set[str]:
    """Корни значимых слов названия отрасли: «аренды» -> «аренд», «растениеводство» -> «растениеводст»."""
    out = set()
    for w in _words(name):
        if len(w) < 5 or w in _NAME_STOP:
            continue
        out.add(w[: max(5, len(w) - 2)])
    return out


def _collapse(roots: set[str]) -> set[str]:
    """Один корень — одно совпадение: из «автомобил» и «автомобилей» оставляем более короткий,
    иначе одно слово в тексте давало бы вес 2 и проходило порог."""
    single = sorted((r for r in roots if " " not in r), key=len)
    kept: list[str] = []
    for r in single:
        if not any(r.startswith(k.rstrip("$")) and not k.endswith("$") and len(k) > SHORT_ROOT
                   for k in kept):
            kept.append(r)
    return set(kept) | {r for r in roots if " " in r}


@lru_cache(maxsize=1)
def _roots() -> dict[str, tuple[tuple[str, ...], ...]]:
    """okved2 -> корни; корень из нескольких слов («торговых сет») — кортеж корней подряд."""
    table: dict[str, set[str]] = {}
    for code, rec in load_map().items():
        table[code] = _name_roots(rec["name"])
    for code, words in SYNONYMS.items():
        table.setdefault(code, set()).update(w.lower().replace("ё", "е") for w in words)
    return {code: tuple(tuple(r.split()) for r in sorted(_collapse(roots))) for code, roots in table.items()}


def _hit(root: tuple[str, ...], words: list[str]) -> bool:
    def same(part: str, word: str) -> bool:
        if part.endswith("$"):
            return word == part[:-1]
        return word == part if len(part) <= SHORT_ROOT else word.startswith(part)

    n = len(root)
    return any(all(same(root[j], words[i + j]) for j in range(n)) for i in range(len(words) - n + 1))


def industry_scores(title: str, text: str) -> dict[str, int]:
    """okved2 -> вес совпадений (только отрасли с весом > 0)."""
    head, lead = _words(title), _words((text or "")[:LEAD_CHARS])
    scores: dict[str, int] = {}
    for code, roots in _roots().items():
        score = 0
        for root in roots:
            if _hit(root, head):
                score += TITLE_WEIGHT
            elif _hit(root, lead):
                score += 1
        if score:
            scores[code] = score
    return scores


def industry_tags(title: str, text: str) -> list[str]:
    """Теги okved:NN для новости: самые сильные отрасли с весом ≥ MIN_SCORE, не больше MAX_TAGS."""
    scores = industry_scores(title, text)
    best = sorted((c for c, s in scores.items() if s >= MIN_SCORE), key=lambda c: (-scores[c], c))
    return [f"{TAG_PREFIX}{c}" for c in best[:MAX_TAGS]]


def okved_codes(tags: Iterable[str]) -> list[str]:
    """Коды отраслей из тегов документа: ["economy", "okved:41"] -> ["41"]."""
    return [t[len(TAG_PREFIX):] for t in tags if isinstance(t, str) and t.startswith(TAG_PREFIX)]


def merge_tags(existing: Iterable[str], industry: Iterable[str]) -> list[str]:
    """Старые теги не трогаем, прежние okved:* заменяем новыми (словарь мог измениться)."""
    keep = [t for t in existing if not (isinstance(t, str) and t.startswith(TAG_PREFIX))]
    return list(dict.fromkeys([*keep, *industry]))


def tag_label(tag: str) -> str:
    """Название отрасли для тега okved:NN (для документации и интерфейса)."""
    code = tag[len(TAG_PREFIX):] if tag.startswith(TAG_PREFIX) else tag
    return (load_map().get(code.zfill(2)) or {}).get("name", "")
